"""Compile design/dao-ways/ drafts into index.md and _new-pieces.md, and print slot-table observations.

Usage: python -I tools/design/dao_ways/compile_index.py [--check]

Reads every NN-slug.md Way draft. Writes:
  design/dao-ways/index.md       one row per Way: number, name, title, needs, directions, capstones, counts
  design/dao-ways/_new-pieces.md every "New pieces" bullet, grouped by label (Needs key / Needs rule / other)
Observations (printed, never a verdict): facets that do not hold exactly 1 major and 2 minors, Ways with capstones
outside 2-6, Ways with more than 4 shared minors, and Ways holding an art. dao.md rule 10 is the rule; this only counts.
"""
import glob
import io
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
DIR = os.path.join(ROOT, "design", "dao-ways")


def parse(path):
    s = io.open(path, encoding="utf-8").read()
    head = s.splitlines()[0]
    m = re.match(r"#\s*(\d+)\s*·\s*(.+?)\s*·\s*\*(.+?)\*\s*\((.+)\)", head)
    w = {"file": os.path.basename(path), "num": int(os.path.basename(path)[:2]), "head": head,
         "archived": "◇" in head.split("·")[1] if "·" in head else False}
    if m:
        w.update(name=m.group(2).strip("◇ ").strip(), title=m.group(3), gloss=m.group(4))
    else:
        w.update(name=head.lstrip("# "), title="", gloss="")
    nm = re.search(r"\*\*Needs:\*\*\s*([^.\n]+)", s)
    w["needs"] = nm.group(1).strip() if nm else "—"
    dsec = re.search(r"## Build directions\n(.*?)\n## ", s, re.S)
    w["directions"] = re.findall(r"^\d+\.\s+\*\*(.+?)\*\*", dsec.group(1), re.M) if dsec else []
    facets = re.split(r"^### ", s, flags=re.M)[1:]
    w["facets"] = []
    for f in facets:
        title = f.splitlines()[0].strip()
        majors = len(re.findall(r"^\s*- \*\*Major:", f, re.M))
        minors = len(re.findall(r"^\s*- Minor:", f, re.M))
        arts = len(re.findall(r"^\s*- \*\*Art:", f, re.M))
        shared = len(re.findall(r"\*Shared minor\*", f))
        w["facets"].append((title, majors, minors, arts, shared))
    csec = re.search(r"## Capstones\n(.*?)(\n## |\Z)", s, re.S)
    w["capstones"] = re.findall(r"^\|\s*\*\*(.+?)\*\*", csec.group(1), re.M) if csec else []
    w["art_way"] = bool(re.search(r"^## Art\b", s, re.M)) or any(a for _, _, _, a, _ in w["facets"])
    nsec = re.search(r"## New pieces\n(.*?)(\n## |\Z)", s, re.S)
    w["new"] = [b.strip() for b in re.findall(r"^- (.+(?:\n  .+)*)", nsec.group(1), re.M)] if nsec else []
    return w


def main():
    ways = [parse(p) for p in sorted(glob.glob(os.path.join(DIR, "[0-9][0-9]-*.md")))]
    obs = []
    rows = ["| # | Way | Title | Needs | Build directions | Capstones | Facets | Majors / minors |",
            "|---|---|---|---|---|---|---|---|"]
    for w in ways:
        if w["archived"]:
            rows.append(f"| {w['num']} | ◇ {w['name']} | *{w['title']}* | — | archived | — | — | — |")
            continue
        maj = sum(f[1] for f in w["facets"])
        mino = sum(f[2] for f in w["facets"])
        shared = sum(f[4] for f in w["facets"])
        dirs = "; ".join(d.rstrip(".") for d in w["directions"])
        caps = "; ".join(w["capstones"])
        rows.append(f"| {w['num']} | [{w['name']}]({w['file']}) | *{w['title']}* | {w['needs']} | {dirs} | {caps} | "
                    f"{len(w['facets'])} | {maj} / {mino} |")
        if w["file"] == "52-kiem.md":
            continue  # summary of the drawn pilot; its region file is the source
        for t, a, b, art, _ in w["facets"]:
            if a != 1 or b != 2:
                obs.append(f"{w['file']}: facet '{t}' holds {a} major, {b} minor")
        if not 2 <= len(w["capstones"]) <= 6:
            obs.append(f"{w['file']}: {len(w['capstones'])} capstones")
        if shared > 4:
            obs.append(f"{w['file']}: {shared} shared minors (max 4)")
        if w["art_way"]:
            obs.append(f"{w['file']}: holds an art")
    live = [w for w in ways if not w["archived"]]
    idx = ["# Đạo Ways: index (overnight drafts)", "",
           "> Generated by `tools/design/dao_ways/compile_index.py`. Do not edit by hand; edit the Way files and rerun.",
           f"> {len(live)} Ways drafted, {len(ways) - len(live)} archived. Kiếm Đạo is the approved pilot (its region file is "
           "the source).", "", *rows, ""]
    io.open(os.path.join(DIR, "index.md"), "w", encoding="utf-8").write("\n".join(idx))

    groups = {"Needs rule": [], "Needs key": [], "Other": []}
    for w in live:
        for b in w["new"]:
            line = re.sub(r"\s+", " ", b)
            g = "Needs rule" if "Needs rule" in line else ("Needs key" if "Needs key" in line else "Other")
            groups[g].append(f"| {w['num']} {w['name']} | {line} |")
    out = ["# Đạo Ways: new pieces register", "",
           "> Generated by `tools/design/dao_ways/compile_index.py` from each Way's **New pieces** section. A row marked",
           "> `Needs rule` asks a GDD to change; `Needs key` asks for a new stat key, status, tag or readable. Many rows",
           "> ask for the same thing from different Ways: the morning report groups those into shared rules.", ""]
    for g, rs in groups.items():
        out += [f"## {g} ({len(rs)})", "", "| Way | Piece |", "|---|---|", *rs, ""]
    io.open(os.path.join(DIR, "_new-pieces.md"), "w", encoding="utf-8").write("\n".join(out))
    print(f"ways: {len(ways)} ({len(live)} drafted); new-piece rows: " + ", ".join(f"{g} {len(r)}" for g, r in groups.items()))
    print("observations:" if obs else "observations: none")
    for o in obs:
        print("  " + o)


if __name__ == "__main__":
    sys.exit(main())
