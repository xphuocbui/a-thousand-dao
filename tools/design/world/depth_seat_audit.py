"""Seat audit for the world-depth pass (design/world/depth/README.md).

Reads assets/data/world_continent.json and writes design/world/depth/seat-audit.md: for every sect, how its seat's
land qi fits its leans, and the best fitting places inside its own ground. An observation, not a verdict: the fit
test is the one written in design/world/depth/rules-proposals.md (R4) and the pick is the author's.

Fit (R4): the first lean is a base element with share >= PRIMARY at the seat (or is the seat's top element); every
other base lean >= SECONDARY or among the seat's top two elements; every variant lean >= VARIANT variant qi. A sect with no lean always fits.

Run: python -I tools/design/world/depth_seat_audit.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
PRIMARY, SECONDARY, VARIANT = 25.0, 15.0, 5.0
E = {"Metal": "kim", "Wood": "moc", "Water": "thuy", "Fire": "hoa", "Earth": "tho"}
V = {"Ice": "bang", "Thunder": "loi", "Wind": "phong", "Darkness": "am", "Light": "quang", "Poison": "am"}
SEAT_OK_KINDS = {"peak", "ruin", "spirit_vein", "lake", "forest", "gorge", "hot_spring", "mine", "beast_lair",
                 "volcano", "lava_vent", "great_seat", "minor_seat", "blessed_land"}


def fit(p, leans):
    q = p["qi"]
    sh, va = q["shares"], q.get("variants", {})
    top = max(sh, key=sh.get)
    top2 = sorted(sh, key=sh.get, reverse=True)[:2]
    notes, ok, margin = [], True, 999.0
    for i, l in enumerate(leans):
        if l in E:
            s = sh.get(E[l], 0.0)
            need = PRIMARY if i == 0 else SECONDARY
            good = s >= need or (i == 0 and top == E[l]) or (i > 0 and E[l] in top2)
            margin = min(margin, s - need)
            notes.append("%s %d%%" % (l, round(s)))
        else:
            s = va.get(V.get(l, ""), 0.0)
            good = s >= VARIANT
            margin = min(margin, s - VARIANT)
            notes.append("%s %d" % (l, round(s)))
        ok = ok and good
    return ok, margin, ", ".join(notes)


def main():
    w = json.loads((ROOT / "assets/data/world_continent.json").read_text(encoding="utf-8"))
    places = w["places"]
    seats = {s["seat"] for s in w["great_sects"] + w["minor_sects"]}
    by_id = {p["id"]: p for p in places}
    out = ["# Seat audit (generated by tools/design/world/depth_seat_audit.py)", "",
           "Fit test R4: first base lean >= %d %% (or the seat's top element), other base leans >= %d %% (or in the top two), variant "
           "leans >= %d variant qi. Candidates: places of the sect's own ground (great: its territory; minor: its "
           "lord's territory in the seat's region), not another sect's seat, best first. Density is the place's qi "
           "density (the current seat's in the header)." % (PRIMARY, SECONDARY, VARIANT), ""]
    n_bad = 0
    for s in w["great_sects"] + w["minor_sects"]:
        seat = by_id[s["seat"]]
        ok, _, notes = fit(seat, s["leans"])
        n_bad += not ok
        great = s in w["great_sects"]
        lord = s["key"] if great else s.get("lord", "")
        cands = []
        for p in places:
            if p["id"] in seats and p["id"] != s["seat"]:
                continue
            if p["kind"] not in SEAT_OK_KINDS:
                continue
            if p.get("territory") != lord:
                continue
            if not great and p["region"] != seat["region"]:
                continue
            f, m, n = fit(p, s["leans"])
            if f:
                cands.append((m, p["density"], p, n))
        cands.sort(key=lambda c: (-min(c[0], 25) - 10 * c[1]))
        out.append("## %s %s (%s; leans %s)" % ("OK " if ok else "MOVE", s["name"], s["key"], "/".join(s["leans"]) or "none"))
        out.append("Seat: %s (id %d, %s, region %d, %s), density %.2f" % (seat["name"], seat["id"], seat["kind"], seat["region"],
                                                                      seat["biome"], seat["density"]))
        out.append("Seat qi: %s" % notes)
        if not ok:
            if cands:
                out.append("Candidates:")
                for m, d, p, n in cands[:6]:
                    out.append("- %s (id %d, %s, region %d, %s, elev %.2f km): %s; density %.2f" % (
                        p["name"], p["id"], p["kind"], p["region"], p["biome"], p["elevation_km"], n, d))
            else:
                out.append("Candidates: none in its own ground; re-lean the sect to its land, or move it to a fitting "
                           "place nearby (see rules-proposals R4).")
        out.append("")
    out.insert(3, "**%d of %d seats fail the fit test.**" % (n_bad, len(w["great_sects"]) + len(w["minor_sects"])))
    out.insert(4, "")
    (ROOT / "design/world/depth/seat-audit.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("seats failing: %d" % n_bad)


if __name__ == "__main__":
    main()
