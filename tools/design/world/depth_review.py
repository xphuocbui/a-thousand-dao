"""Content review statistics for the world-depth pass (observations, not verdicts).

Writes design/world/depth/review/script-findings.md with:
1. plot shapes: motif counts across sect pages' sections 9 and 12, and backstories
2. dates: new-event years and seat-move years, clustered
3. voice tics: stock phrases and the most repeated 4-word phrases across backstories
4. timeline: parent/child age gaps, dead parents of later-born children, master age gaps, spouse gaps
5. build coherence: weapon base vs archetype, tree start vs main method element, identical routes within a sect
6. trait spread: personality and calling frequencies, unused v2 traits

Run: python -I tools/design/world/depth_review.py
"""
import collections
import glob
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
D = ROOT / "design/world/depth"
OUT = D / "review"


def load(p):
    return json.loads(pathlib.Path(p).read_text(encoding="utf-8"))


def main():
    OUT.mkdir(exist_ok=True)
    people, src = {}, {}
    for f in glob.glob(str(D / "**/*.cast.json"), recursive=True):
        for p in load(f)["people"]:
            people[p["key"]] = p
            src[p["key"]] = pathlib.Path(f).name
    pages = {pathlib.Path(f).stem: pathlib.Path(f).read_text(encoding="utf-8") for f in glob.glob(str(D / "sects/*.md"))}
    L = ["# Script findings (generated by tools/design/world/depth_review.py)", "",
         "Observations to steer the readers' review; counts, not verdicts.", ""]

    # 1. plot shapes
    motifs = {
        "passed over for the headship": r"passed over",
        "succession / heir quarrel": r"\bheir\b|succession",
        "a secret kept from the sect": r"has told no one|told no one|tells no one|never told",
        "a hidden root or variant": r"hid(es|den)? (a|her|his) .*root|hidden root|hides (a|her|his) (darkness|variant)",
        "the last of a fallen sect / line": r"\bthe last of\b|last survivor",
        "a dying elder near lifespan's end": r"waning|end of (his|her|a) .*life|near the end of",
        "the one breakthrough pill": r"breakthrough pill",
        "a hostage": r"hostage|surety",
        "a lost treasure to recover": r"\blost\b.*(sword|item|treasure|manual)|recover",
        "a tempter from the demonic path": r"ma đạo|demonic|tempt",
        "never forgiven": r"never forg(i|a)ve",
        "an old war grudge": r"grudge",
    }
    sec_text = {k: (re.split(r"\n## 9\.", v, 1) + [""])[1] for k, v in pages.items()}
    bs = {k: str(p.get("backstory", "")) for k, p in people.items()}
    L.append("## 1. Plot shapes")
    L.append("| Motif | sect pages (sections 9-12) | backstories |")
    L.append("|---|---|---|")
    for name, rx in motifs.items():
        n_pages = sum(1 for t in sec_text.values() if re.search(rx, t, re.I))
        n_bs = sum(1 for t in bs.values() if re.search(rx, t, re.I))
        L.append("| %s | %d of %d | %d of %d |" % (name, n_pages, len(sec_text), n_bs, len(bs)))
    L.append("")

    # 2. dates
    yrs = collections.Counter()
    for k, t in pages.items():
        for m in re.finditer(r"\|\s*(\d{3,4})(?:\s*[-–]\s*\d{3,4})?\s*\|[^\n]*N-[a-z_]+-\d+", t):
            yrs[int(m.group(1)) // 10 * 10] += 1
    moves = {}
    for k, t in pages.items():
        head = t.split("## 3.")[0]
        m = re.search(r"\b(1[01]\d\d|[4-9]\d\d)\b", (re.search(r"\| Seat \|[^\n]*", head) or re.search("x", "x")).group(0))
        if m and "move" in head.lower():
            moves[k] = int(m.group(1))
    L.append("## 2. Dates")
    L.append("New `N-` events by decade, busiest: " + ", ".join("%ds %d" % (d, n) for d, n in yrs.most_common(12)))
    L.append("")
    L.append("Seat-move years read from the pages' Seat rows: " + ", ".join("%s %d" % (k, y) for k, y in sorted(moves.items(), key=lambda x: x[1])))
    L.append("")

    # 3. voice tics
    stock = ["has told no one", "never forgiven", "does not know", "has never", "the only one", "in secret", "quietly",
             "she has not", "he has not", "not yet", "the last", "for forty years", "every winter", "every year"]
    L.append("## 3. Voice tics")
    L.append("| Phrase | backstories |")
    L.append("|---|---|")
    for s in stock:
        L.append("| \"%s\" | %d |" % (s, sum(1 for t in bs.values() if s in t.lower())))
    grams = collections.Counter()
    for t in bs.values():
        w = re.findall(r"[a-zà-ỹ']+", t.lower())
        seen = set()
        for i in range(len(w) - 3):
            g = " ".join(w[i:i + 4])
            if g not in seen:
                grams[g] += 1
                seen.add(g)
    L.append("")
    L.append("Most repeated 4-word phrases (backstories containing them): " +
             "; ".join("\"%s\" %d" % (g, n) for g, n in grams.most_common(25)))
    L.append("")

    # 4. timeline
    issues = []
    for k, p in people.items():
        for t in p.get("ties", []):
            o = people.get(t.get("to"))
            if not o:
                continue
            kind = t.get("kind")
            if kind == "parent":
                gap = int(p.get("born", 0)) - int(o.get("born", 0))
                if gap < 16:
                    issues.append("%s: parent %s only %d years older" % (k, o["key"], gap))
                if not o.get("alive", True) and int(o.get("died", 9999)) < int(p.get("born", 0)) - 1:
                    issues.append("%s: parent %s died %s, before this birth %s" % (k, o["key"], o.get("died"), p.get("born")))
            if kind in ("master",) and int(o.get("born", 0)) > int(p.get("born", 0)) - 10:
                issues.append("%s: master %s less than 10 years older" % (k, o["key"]))
            if kind in ("spouse", "dao_partner") and abs(int(o.get("born", 0)) - int(p.get("born", 0))) > 400:
                issues.append("%s: %s %s born %d years apart" % (k, kind, o["key"], abs(int(o.get("born", 0)) - int(p.get("born", 0)))))
    L.append("## 4. Timeline (%d observations)" % len(issues))
    L += ["- " + x for x in issues[:80]]
    L.append("")

    # 5. build coherence
    # linh_thuc_su is the spirit farmer (no weapon base); bells, lanterns and banners are this world's array tools
    weapon_of = {"kiem_tu": {"phi_kiem"}, "dan_su": {"huong_lo", "ho_lo"},
                 "tran_su": {"ky", "an", "kinh", "co", "chuong", "dang", "phien"},
                 "the_tu": {"giap", "thuan", "lac_thiet", "mao", "loi_truong"}}
    items = {}
    for f in glob.glob(str(D / "**/*.items.json"), recursive=True):
        for i in load(f).get("items", []):
            items[i["id"]] = i
    for f in glob.glob(str(ROOT / "design/items/catalogue-*.json")):
        for i in load(f):
            items[i["id"]] = i
    miss = collections.Counter()
    miss_ex = collections.defaultdict(list)
    routes = collections.defaultdict(list)
    for k, p in people.items():
        b = p.get("build") or {}
        if not p.get("alive", True) or not b:
            continue
        bases = set()
        for g in b.get("gear", []):
            bases.add(g.get("base") or items.get(g.get("named"), {}).get("base"))
        want = weapon_of.get(b.get("archetype"))
        if want and p.get("tier") in ("A", "B") and not (bases & want):
            miss[b.get("archetype")] += 1
            miss_ex[b.get("archetype")].append(k)
        tg = tuple((b.get("tree") or {}).get("targets") or [])
        if tg and p.get("sect"):
            routes[(p["sect"], tg)].append(k)
    L.append("## 5. Build coherence")
    L.append("Tier A/B builds whose gear carries none of their archetype's usual bases: " +
             ", ".join("%s %d (e.g. %s)" % (a, n, ", ".join(miss_ex[a][:4])) for a, n in miss.most_common()))
    dup = [(s, ks) for (s, tg), ks in routes.items() if len(ks) > 1]
    L.append("")
    L.append("Identical Đạo Đồ routes shared by more than one person in a sect: %d groups, e.g. %s" % (
        len(dup), "; ".join("%s: %s" % (s, ", ".join(ks)) for s, ks in dup[:12])))
    L.append("")

    # 6. trait spread
    pers = collections.Counter()
    call = collections.Counter()
    v2used = collections.Counter()
    for p in people.values():
        tr = p.get("traits") or {}
        pers.update(tr.get("personality", []))
        if tr.get("calling"):
            call[tr["calling"]] += 1
        for kind in ("upbringing", "lifestyle", "health", "coping"):
            if tr.get(kind):
                v2used[tr[kind]] += 1
        for x in tr.get("path", []) or []:
            v2used[x] += 1
        for x in tr.get("talent", []) or []:
            v2used[x.get("id")] += 1
    t2 = load(D / "traits-v2.json")
    allv2 = {x["id"] for k in t2["kinds"] for x in t2[k]}
    L.append("## 6. Trait spread")
    L.append("Personality, most used: " + ", ".join("%s %d" % x for x in pers.most_common(10)))
    L.append("")
    L.append("Personality, least used: " + ", ".join("%s %d" % x for x in pers.most_common()[-10:]))
    L.append("")
    L.append("Callings: " + ", ".join("%s %d" % x for x in call.most_common()))
    L.append("")
    L.append("v2 traits never used: " + ", ".join(sorted(allv2 - set(v2used))))
    L.append("")
    L.append("v2 traits, most used: " + ", ".join("%s %d" % x for x in v2used.most_common(12)))
    (OUT / "script-findings.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote review/script-findings.md: %d people, %d pages, %d timeline observations" % (len(people), len(pages), len(issues)))


if __name__ == "__main__":
    main()
