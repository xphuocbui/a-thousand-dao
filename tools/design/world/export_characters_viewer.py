"""Export standardized character data and offline HTML viewer for all authored cast and Spirit Beasts.

Reads read-only game data under assets/data/ and portrait file presence under
assets/portraits/cast/, then writes:
  - docs/characters/characters.json      (schema_version: 1, formatted UTF-8 JSON)
  - docs/characters/characters.data.js   (single-line UTF-8 window.CHARACTERS_DATA = ...;)
  - docs/characters/index.html           (self-contained offline viewer, zero external CDNs)

CLI flags:
  (default)             Write the three files under docs/characters/.
  --check               Verify all 3 generated files exist and match exact generated bytes.
  --selftest            Validate dataset counts, Formula E ratings, portraits, and references.
  --preview-html PATH   Write a compact (< 420 KB) self-contained T3 preview HTML file.
"""

