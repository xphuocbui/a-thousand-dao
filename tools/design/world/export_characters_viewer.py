def render_json_bytes(dataset: dict[str, Any]) -> bytes:
    return (json.dumps(dataset, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def render_data_js_bytes(dataset: dict[str, Any]) -> bytes:
    # Escape </script> defensively in case any string ever contains it
    payload = json.dumps(dataset, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    return f"window.CHARACTERS_DATA = {payload};\n".encode("utf-8")


