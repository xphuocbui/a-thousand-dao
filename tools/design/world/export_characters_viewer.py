def run_selftest(dataset: dict[str, Any], repo_root: Path = REPO_ROOT) -> list[str]:
    errors: list[str] = []
    data_dir = repo_root / "assets" / "data"

    cr = load_json(data_dir / "cast_ratings.json")
    cp = load_json(data_dir / "items_cong_phap.json")
    named_data = load_json(data_dir / "items_named.json")
    art_data = load_json(data_dir / "items_artifacts.json")
    sets_data = load_json(data_dir / "items_sets.json")

    counts = dataset["counts"]
    expected_counts = {
        "total": 1930,
        "living_cast": 1748,
        "dead_cast": 161,
        "beasts": 21,
        "rated": 1769,
        "with_portrait": 1909,
    }
    for k, exp in expected_counts.items():
        if counts.get(k) != exp:
            errors.append(f"counts.{k} = {counts.get(k)}, expected {exp}")

    chars = dataset["characters"]
    if len(chars) != 1930:
        errors.append(f"len(characters) = {len(chars)}, expected 1930")

    all_ids = {c["id"] for c in chars}
    if len(all_ids) != len(chars):
        errors.append("Duplicate character ids detected")

    sect_ids = set(dataset["lookups"]["sects"].keys())
    traits_lookup = dataset["lookups"]["traits"]
    trait_ids = set(traits_lookup.keys())
    tech_ids = {str(t["id"]) for t in cp["templates"]}
    named_ids = {str(n["id"]) for n in named_data["named"]}
    base_ids = {str(b["id"]) for b in art_data["bases"]}
    set_ids = {str(s["id"]) for s in sets_data["sets"]}

    trait_icons_on_disk = 0
    for tid, tentry in traits_lookup.items():
        if not isinstance(tentry.get("meaning"), str):
            errors.append(f"lookups.traits.{tid}: meaning is not a str")
        effs = tentry.get("effects")
        if not isinstance(effs, list) or not all(isinstance(x, str) for x in effs):
            errors.append(f"lookups.traits.{tid}: effects is not a list[str]")
        ico = tentry.get("icon")
        if not isinstance(ico, dict) or not {"has_file", "path", "rel_from_viewer"}.issubset(ico.keys()):
            errors.append(f"lookups.traits.{tid}: icon missing required dict keys")
        elif ico["has_file"]:
            ico_path = repo_root / str(ico["path"])
            if not str(ico["path"]).endswith(".png") or not ico_path.is_file():
                errors.append(f"lookups.traits.{tid}: icon marked has_file=True but missing .png at {ico_path}")
            else:
                trait_icons_on_disk += 1
                if ico["rel_from_viewer"] != f"../../{ico['path']}":
                    errors.append(f"lookups.traits.{tid}: icon rel_from_viewer mismatch ({ico['rel_from_viewer']})")
        else:
            if ico["path"] != "" or ico["rel_from_viewer"] != "":
                errors.append(f"lookups.traits.{tid}: icon has_file=False must have empty path and rel_from_viewer")

    if trait_icons_on_disk < 71:
        errors.append(f"trait_icons_on_disk = {trait_icons_on_disk}, expected >= 71")

    expected_char_keys = tuple(chars[0].keys())
    expected_trait_keys = TRAIT_BUCKET_KEYS

    rated_seen = 0
    portrait_on_disk = 0
    for c in chars:
        cid = c["id"]
        if tuple(c.keys()) != expected_char_keys:
            errors.append(f"{cid}: character top-level keys differ from uniform schema")
        if tuple(c["traits"].keys()) != expected_trait_keys:
            errors.append(f"{cid}: traits keys {tuple(c['traits'].keys())} != {expected_trait_keys}")
        for cat, items in c["traits"].items():
            if not isinstance(items, list):
                errors.append(f"{cid}: traits.{cat} is not a list")
            else:
                for t in items:
                    if t["id"] not in trait_ids:
                        errors.append(f"{cid}: unresolved trait id {t['id']}")

        if c["sect"]["id"] and c["sect"]["id"] not in sect_ids:
            errors.append(f"{cid}: unresolved sect id {c['sect']['id']}")

        if c["master"] is not None and c["master"]["id"] not in all_ids:
            errors.append(f"{cid}: unresolved master id {c['master']['id']}")

        if c["owner"] is not None and c["owner"]["id"] not in all_ids:
            errors.append(f"{cid}: unresolved owner id {c['owner']['id']}")

        for b_ref in c["beasts"]:
            if b_ref["id"] not in all_ids:
                errors.append(f"{cid}: unresolved beast ref {b_ref['id']}")

        for tie in c["ties"]:
            if tie["other_id"] not in all_ids:
                errors.append(f"{cid}: unresolved tie target {tie['other_id']}")

        if c["portrait"]["has_file"]:
            p_path = repo_root / c["portrait"]["path"]
            if p_path.is_file():
                portrait_on_disk += 1
            else:
                errors.append(f"{cid}: portrait marked has_file=True but missing at {p_path}")

        if c["rating"] is not None:
            rated_seen += 1
            if cid not in cr["entries"]:
                errors.append(f"{cid}: rated in output but absent in cast_ratings.json")
            else:
                exp_elo = float(cr["entries"][cid]["base"])
                if abs(c["rating"]["elo"] - exp_elo) > 1e-6:
                    errors.append(f"{cid}: elo {c['rating']['elo']} != {exp_elo}")
        elif cid in cr["entries"]:
            errors.append(f"{cid}: present in cast_ratings.json but rating is None")

        b = c["build"]
        if b is not None:
            mt = b["main_technique"]
            if mt is not None and mt["id"] not in tech_ids:
                errors.append(f"{cid}: unresolved main_technique {mt['id']}")
            for at in b["aux_techniques"]:
                if at["id"] not in tech_ids:
                    errors.append(f"{cid}: unresolved aux_technique {at['id']}")
            for g in b["gear"]:
                if g["id"] not in named_ids and g["id"] not in base_ids:
                    errors.append(f"{cid}: unresolved gear item {g['id']}")
            for st in b["sets"]:
                if st["id"] not in set_ids:
                    errors.append(f"{cid}: unresolved set id {st['id']}")

    if rated_seen != 1769:
        errors.append(f"rated_seen = {rated_seen}, expected 1769")
    if portrait_on_disk != 1909:
        errors.append(f"portrait_on_disk = {portrait_on_disk}, expected 1909")

    # Verify global_rank sequence 1..1769
    ranks = [c["rating"]["global_rank"] for c in chars if c["rating"] is not None]
    if ranks != list(range(1, 1770)):
        errors.append("global_rank sequence is not strictly 1..1769 in canonical order")

    return errors


def run_check(expected_files: dict[Path, bytes]) -> list[str]:
    diffs: list[str] = []
    for path, expected in expected_files.items():
        if not path.is_file():
            diffs.append(f"MISSING: {path}")
            continue
        actual = path.read_bytes()
        if actual != expected:
            diffs.append(f"DRIFT: {path} (on-disk {len(actual)} bytes != generated {len(expected)} bytes)")
    return diffs


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export standardized characters JSON and offline HTML viewer.")
    parser.add_argument("--check", action="store_true", help="Verify docs/characters/* match generated bytes.")
    parser.add_argument("--selftest", action="store_true", help="Validate schema, counts, ratings, portraits, and refs.")
    parser.add_argument("--preview-html", metavar="PATH", help="Write compact (<420 KB) self-contained T3 preview HTML.")
    args = parser.parse_args(argv)

    dataset = build_dataset(REPO_ROOT)

    if args.preview_html:
        preview_bytes = render_preview_html(dataset, REPO_ROOT)
        out_path = Path(args.preview_html)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_bytes(preview_bytes)
        print(f"Wrote preview HTML: {out_path} ({len(preview_bytes):,} bytes)")
        if len(preview_bytes) >= 420 * 1024:
            print(f"ERROR: preview HTML exceeds 420 KB ({len(preview_bytes):,} bytes)", file=sys.stderr)
            return 1

    expected_files: dict[Path, bytes] = {
        OUT_DIR / "characters.json": render_json_bytes(dataset),
        OUT_DIR / "characters.data.js": render_data_js_bytes(dataset),
        OUT_DIR / "index.html": render_viewer_html(),
    }

    if not args.check and not args.selftest and not args.preview_html:
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        for path, content in expected_files.items():
            path.write_bytes(content)
            print(f"Wrote {path.relative_to(REPO_ROOT)} ({len(content):,} bytes)")
        return 0

    exit_code = 0
    if args.check:
        diffs = run_check(expected_files)
        if diffs:
            for d in diffs:
                print(d, file=sys.stderr)
            exit_code = 1
        else:
            print("CHECK OK: docs/characters/characters.json, characters.data.js, and index.html match generated bytes.")

    if args.selftest:
        errs = run_selftest(dataset, REPO_ROOT)
        if errs:
            for e in errs[:40]:
                print(f"SELFTEST FAIL: {e}", file=sys.stderr)
            if len(errs) > 40:
                print(f"... and {len(errs) - 40} more errors", file=sys.stderr)
            exit_code = 1
        else:
            ct = dataset["counts"]
            t_total = len(dataset["lookups"]["traits"])
            t_icons = sum(1 for t in dataset["lookups"]["traits"].values() if t["icon"]["has_file"])
            print(
                f"SELFTEST OK: {ct['total']} total ({ct['living_cast']} living + {ct['dead_cast']} dead + {ct['beasts']} beasts), "
                f"{ct['rated']} rated, {ct['with_portrait']} portraits, {t_total} traits ({t_icons} icons) verified."
            )

    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
