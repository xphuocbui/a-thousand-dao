def select_preview_slice(dataset: dict[str, Any]) -> list[dict[str, Any]]:
    """Select a representative ~45-character slice spanning all realms, beasts, and dead founders."""
    chars = dataset["characters"]
    picked_ids: set[str] = set()
    ordered: list[dict[str, Any]] = []

    def take(pred, limit: int) -> None:
        count = 0
        for c in chars:
            if count >= limit:
                break
            if c["id"] not in picked_ids and pred(c):
                picked_ids.add(c["id"])
                ordered.append(c)
                count += 1

    # Top 15 overall rated (includes both Hoa Than + top Nguyen Anh)
    take(lambda c: c["rating"] is not None, 15)
    # Ensure both Hoa Than
    take(lambda c: c["status"] == "living" and c["realm"]["id"] == "hoa_than", 2)
    # Top 6 each for Ket Dan, Truc Co, Luyen Khi
    take(lambda c: c["status"] == "living" and c["realm"]["id"] == "ket_dan", 6)
    take(lambda c: c["status"] == "living" and c["realm"]["id"] == "truc_co", 6)
    take(lambda c: c["status"] == "living" and c["realm"]["id"] == "luyen_khi", 6)
    # Top 8 Spirit Beasts
    take(lambda c: c["status"] == "beast", 8)
    # Top 8 Historical Dead Founders/Legends
    take(lambda c: c["status"] == "dead", 8)

    # Preserve canonical order from dataset
    id_order = {c["id"]: idx for idx, c in enumerate(chars)}
    ordered.sort(key=lambda c: id_order[c["id"]])
    return ordered


def build_inline_thumbnails(slice_chars: list[dict[str, Any]], repo_root: Path, max_thumbs: int = 20) -> dict[str, str]:
    """Generate small 64x96 WebP/JPEG data URIs for up to max_thumbs top cast portraits."""
    try:
        from PIL import Image
    except Exception:
        return {}

    thumbs: dict[str, str] = {}
    for c in slice_chars:
        if len(thumbs) >= max_thumbs:
            break
        if not c["portrait"]["has_file"]:
            continue
        p = repo_root / c["portrait"]["path"]
        if not p.is_file():
            continue
        try:
            with Image.open(p) as im:
                im = im.convert("RGB")
                im.thumbnail((64, 96), Image.Resampling.LANCZOS)
                buf = io.BytesIO()
                try:
                    im.save(buf, format="WEBP", quality=72, method=4)
                    mime = "image/webp"
                except Exception:
                    buf = io.BytesIO()
                    im.save(buf, format="JPEG", quality=72, optimize=True)
                    mime = "image/jpeg"
                b64 = base64.b64encode(buf.getvalue()).decode("ascii")
                thumbs[c["id"]] = f"data:{mime};base64,{b64}"
        except Exception:
            continue
    return thumbs


