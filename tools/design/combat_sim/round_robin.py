"""Round robin: every build against every other build of the same realm, plus the typical build, on engine v2.

Emits observations, not a verdict. Reads design/builds/engine-v2/builds/<id>.fight.json (each build's defining realm;
<id>.<realm>.fight.json files join the round robin of that realm too). A file fight.py refuses is listed as
NOT ASSESSED with the reason, never dropped silently.

Run: python -I tools/design/combat_sim/round_robin.py [--seeds 10] [--out design/builds/engine-v2/ROUND-ROBIN.md]
"""
import argparse
import glob
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, ".claude", "skills", "design-build", "scripts"))
_argv, sys.argv = sys.argv, sys.argv[:1]
import fight  # noqa: E402
import engine  # noqa: E402
sys.argv = _argv


def load(seeds_dir):
    by_realm, bad = {}, []
    for f in sorted(glob.glob(os.path.join(seeds_dir, "*.fight.json"))):
        name = os.path.basename(f)[:-len(".fight.json")]
        try:
            d = fight.expand_library(json.load(open(f, encoding="utf-8")))
            r = fight.realm_index(d.get("realm", "luyen_khi"))
            b = fight.to_build(d, r, [], name)
        except (ValueError, OSError, fight.BadInput, engine.EngineError) as e:
            bad.append((name, str(e).splitlines()[0][:160]))
            continue
        by_realm.setdefault(r, []).append((name, b))
    return by_realm, bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=10)
    ap.add_argument("--dir", default=os.path.join(ROOT, "design", "builds", "engine-v2", "builds"))
    ap.add_argument("--out", default=os.path.join(ROOT, "design", "builds", "engine-v2", "ROUND-ROBIN.md"))
    a = ap.parse_args()
    by_realm, bad = load(a.dir)
    if not by_realm:
        print("NO_INPUT\tno fight files loaded from %s" % a.dir)
        return 2
    L = ["# Builds Round Robin", "",
         "> Generated by `tools/design/combat_sim/round_robin.py` (%d seeds per pair, engine v2). Every build against "
         "every other build of the same realm, plus the typical build. Observations, not verdicts." % a.seeds, ""]
    if bad:
        L += ["## Not assessed", "", "| File | Why |", "|---|---|"] + ["| %s | %s |" % x for x in bad] + [""]
    for r in sorted(by_realm):
        items = [("TYPICAL", fight.to_build(fight.enemy_file("typical", r), r, [], "typical"))] + by_realm[r]
        n = len(items)
        W = [[0] * n for _ in range(n)]
        T = [0.0] * n
        G = [0] * n
        for i in range(n):
            for j in range(i + 1, n):
                for s in range(a.seeds):
                    res = engine.fight(items[i][1], items[j][1], seed=s)
                    W[i][j] += res["win"] == "A"
                    W[j][i] += res["win"] == "B"
                    T[i] += res["t"]
                    T[j] += res["t"]
                    G[i] += 1
                    G[j] += 1
        rate = [sum(W[i]) / max(1, G[i]) for i in range(n)]
        order = sorted(range(n), key=lambda i: -rate[i])
        L += ["## %s (%d builds)" % (fight.REALMS[r], n - 1), "",
              "| Rank | Build | Win % | Mean fight s | Beats | Loses to |", "|---|---|---|---|---|---|"]
        for k, i in enumerate(order):
            beats = [items[j][0] for j in range(n) if j != i and W[i][j] > W[j][i]]
            loses = [items[j][0] for j in range(n) if j != i and W[i][j] < W[j][i]]
            L.append("| %d | %s | %.0f | %.1f | %d | %s |" % (k + 1, items[i][0], 100 * rate[i], T[i] / max(1, G[i]),
                                                            len(beats), ", ".join(loses) or "-"))
        L.append("")
        if n <= 16:
            L += ["Head to head (row's wins out of %d against the column):" % a.seeds, "",
                  "| | " + " | ".join(items[i][0][:10] for i in order) + " |",
                  "|---" * (n + 1) + "|"]
            for i in order:
                L.append("| %s | " % items[i][0] + " | ".join("-" if i == j else str(W[i][j]) for j in order) + " |")
            L.append("")
        print("realm %s: %d builds" % (fight.REALMS[r], n - 1))
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote %s; not assessed %d" % (a.out, len(bad)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
