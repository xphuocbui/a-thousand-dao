"""Compile the named-item catalogue (design/items/catalogue-*.json) into game data.

Writes assets/data/items_named.json, the authored named-item templates the game reads (Item Database rule 20).
The design catalogue stays the source; run this after any catalogue change:

    python -I tools/design/items/export_named.py            # write
    python -I tools/design/items/export_named.py --check    # exit 1 if the game data is stale

What is kept per template: id, name, base, grade, element (the five Ngũ Hành families, and Ice, Thunder, Wind and Force-Chaos
as the variant roots Băng, Lôi, Phong and Hỗn Độn), modifiers (key, value, scope), Effects by name, the arts, wards and reserve arts the
piece gives (id, name, rule; the game has no art system yet, so they are stored, not run), sources, holder, and the
`exception` note of rule 21 when there is one. Lore and build notes stay in the design catalogue.
"""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
OUT = os.path.join(ROOT, "assets", "data", "items_named.json")
SETS_OUT = os.path.join(ROOT, "assets", "data", "items_sets.json")   # Item Database rule 22 (ADR-0009, 2026-11-26)

# Design family -> Godot element or variant-root id (character_elements.json; user decision 2026-11-13: the variant
# families map to their variant roots). Blade, body, general and soul-song-seal are not elements and get "".
FAMILY_ELEMENT = {"fire": "hoa", "water": "thuy", "wood": "moc", "metal": "kim", "earth": "tho",
                  "ice": "bang", "thunder": "loi", "wind": "phong", "force-chaos": "hon_don"}


def _art(a):
    out = {"id": a["id"], "name": a.get("name", a["id"]), "rule": a.get("rule", "")}
    for k in ("group", "reserve"):
        if k in a:
            out[k] = a[k]
    return out


def build():
    items = []
    for path in sorted(glob.glob(os.path.join(ROOT, "design", "items", "catalogue-*.json"))):
        with open(path, encoding="utf-8") as f:
            for it in json.load(f):
                if it.get("kind") != "artifact":
                    continue
                rec = {
                    "id": it["id"],
                    "name": it["name"],
                    "base": it["base"],
                    "grade": int(it["grade"]),
                    "element": FAMILY_ELEMENT.get(it.get("family", ""), ""),
                    "family": it.get("family", ""),
                    "modifiers": [{"key": m["key"], "value": m["value"], "scope": m.get("scope", [])}
                                  for m in it.get("modifiers", [])],
                    "effects": list(it.get("effects", [])),
                    "arts": [_art(a) for a in it.get("arts", [])],
                    "wards": [_art(a) for a in it.get("wards", [])],
                    "reserve_arts": [_art(a) for a in it.get("reserve_arts", [])],
                    "sources": list(it.get("sources", [])),
                }
                if it.get("holder"):
                    rec["holder"] = it["holder"]
                if it.get("exception"):
                    rec["exception"] = it["exception"]
                items.append(rec)
    items.sort(key=lambda r: r["id"])
    return {
        "schema_version": 1,
        "_doc": "Generated by tools/design/items/export_named.py from design/items/catalogue-*.json. Do not edit by "
                "hand. Item Database rule 20: authored named artifacts; generation never rolls one.",
        "named": items,
    }


def render(data):
    head = '{\n  "schema_version": %d,\n  "_doc": %s,\n  "named": [\n' % (
        data["schema_version"], json.dumps(data["_doc"], ensure_ascii=False))
    rows = ",\n".join("    " + json.dumps(r, ensure_ascii=False) for r in data["named"])
    return head + rows + "\n  ]\n}\n"


def build_sets():
    """assets/data/items_sets.json from design/items/sets-<key>.json (world-depth sets, ADR-0009): the file's _doc and
    constants are kept; each set is {id, name, pieces, bonuses, story}. A full-set bonus names its Effect, whose engine
    record lives in combat_effects.json under that name (fight.py add_sets); an inline `record` is kept if a set has one."""
    with open(SETS_OUT, encoding="utf-8") as f:
        data = json.load(f)
    sets = []
    for path in sorted(glob.glob(os.path.join(ROOT, "design", "items", "sets-*.json"))):
        with open(path, encoding="utf-8") as f:
            for st in json.load(f):
                rec = {"id": st["id"], "name": st["name"], "pieces": list(st["pieces"]), "bonuses": []}
                for b in st.get("bonuses", []):
                    out = {"pieces": int(b["pieces"])}
                    if b.get("modifiers"):
                        out["modifiers"] = [{"key": m["key"], "value": m["value"], "scope": m.get("scope", [])}
                                            for m in b["modifiers"]]
                    for k in ("effect", "record"):
                        if b.get(k):
                            out[k] = b[k]
                    rec["bonuses"].append(out)
                if st.get("story"):
                    rec["story"] = st["story"]
                sets.append(rec)
    sets.sort(key=lambda r: r["id"])
    data["sets"] = sets
    return data


def render_sets(data):
    """One set per line, the head as json.dumps writes it (indent 2)."""
    head = json.dumps({k: v for k, v in data.items() if k != "sets"}, indent=2, ensure_ascii=False)
    rows = ",\n".join("    " + json.dumps(r, ensure_ascii=False) for r in data["sets"])
    return head[:-2] + ',\n  "sets": [' + ("\n" + rows + "\n  " if rows else "") + "]\n}\n"


def main():
    text = render(build())
    sets_text = render_sets(build_sets())
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        cur_sets = open(SETS_OUT, encoding="utf-8").read() if os.path.exists(SETS_OUT) else ""
        stale = [n for n, a, b in (("items_named.json", cur, text), ("items_sets.json", cur_sets, sets_text)) if a != b]
        if stale:
            print("%s stale: run tools/design/items/export_named.py" % " and ".join(stale))
            sys.exit(1)
        print("items_named.json and items_sets.json are current")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    with open(SETS_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(sets_text)
    print("wrote %s (%d named items) and %s (%d sets)" % (
        os.path.relpath(OUT, ROOT), len(json.loads(text)["named"]), os.path.relpath(SETS_OUT, ROOT),
        len(json.loads(sets_text)["sets"])))


if __name__ == "__main__":
    main()
