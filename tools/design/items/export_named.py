"""Compile the named-item catalogue (design/items/catalogue-*.json) into game data.

Writes assets/data/items_named.json, the authored named-item templates the game reads (Item Database rule 20).
The design catalogue stays the source; run this after any catalogue change:

    python -I tools/design/items/export_named.py            # write
    python -I tools/design/items/export_named.py --check    # exit 1 if the game data is stale

What is kept per template: id, name, base, grade, element (the five Ngũ Hành families only; Ice, Thunder, Wind and the
rest carry no Godot element yet), modifiers (key, value, scope), Effects by name, the arts, wards and reserve arts the
piece gives (id, name, rule; the game has no art system yet, so they are stored, not run), sources, holder, and the
`exception` note of rule 21 when there is one. Lore and build notes stay in the design catalogue.
"""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
OUT = os.path.join(ROOT, "assets", "data", "items_named.json")

# Design family -> Godot element id (character_elements.json). Families without one get "".
FAMILY_ELEMENT = {"fire": "hoa", "water": "thuy", "wood": "moc", "metal": "kim", "earth": "tho"}


def _art(a):
    out = {"id": a["id"], "name": a.get("name", a["id"]), "rule": a.get("rule", "")}
    for k in ("group", "reserve"):
        if k in a:
            out[k] = a[k]
    return out


def build():
    items = []
    for path in sorted(glob.glob(os.path.join(ROOT, "design", "items", "catalogue-*.json"))):
        with open(path, encoding="utf-8") as f:
            for it in json.load(f):
                if it.get("kind") != "artifact":
                    continue
                rec = {
                    "id": it["id"],
                    "name": it["name"],
                    "base": it["base"],
                    "grade": int(it["grade"]),
                    "element": FAMILY_ELEMENT.get(it.get("family", ""), ""),
                    "family": it.get("family", ""),
                    "modifiers": [{"key": m["key"], "value": m["value"], "scope": m.get("scope", [])}
                                  for m in it.get("modifiers", [])],
                    "effects": list(it.get("effects", [])),
                    "arts": [_art(a) for a in it.get("arts", [])],
                    "wards": [_art(a) for a in it.get("wards", [])],
                    "reserve_arts": [_art(a) for a in it.get("reserve_arts", [])],
                    "sources": list(it.get("sources", [])),
                }
                if it.get("holder"):
                    rec["holder"] = it["holder"]
                if it.get("exception"):
                    rec["exception"] = it["exception"]
                items.append(rec)
    items.sort(key=lambda r: r["id"])
    return {
        "schema_version": 1,
        "_doc": "Generated by tools/design/items/export_named.py from design/items/catalogue-*.json. Do not edit by "
                "hand. Item Database rule 20: authored named artifacts; generation never rolls one.",
        "named": items,
    }


def render(data):
    head = '{\n  "schema_version": %d,\n  "_doc": %s,\n  "named": [\n' % (
        data["schema_version"], json.dumps(data["_doc"], ensure_ascii=False))
    rows = ",\n".join("    " + json.dumps(r, ensure_ascii=False) for r in data["named"])
    return head + rows + "\n  ]\n}\n"


def main():
    text = render(build())
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("items_named.json is stale: run tools/design/items/export_named.py")
            sys.exit(1)
        print("items_named.json is current")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d named items)" % (os.path.relpath(OUT, ROOT), len(json.loads(text)["named"])))


if __name__ == "__main__":
    main()
