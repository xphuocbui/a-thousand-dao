"""Write design/items/_logs/brief.md: the lookup tables a catalogue session needs, drawn from the GDDs and the lint.

Run (from the repo root): python -I tools/design/items/make_brief.py
"""
import importlib.util
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
spec = importlib.util.spec_from_file_location("lint_items", os.path.join(os.path.dirname(__file__), "lint_items.py"))
L = importlib.util.module_from_spec(spec)
spec.loader.exec_module(L)


def main():
    gd = L.cat.build()
    stats_w = {s["key"]: s["w"] for s in gd["stats"] if s.get("w") is not None}
    names = {}
    for s in gd["stats"]:
        names.setdefault(s["key"], s["name"])
    wa = L.w_affix(stats_w)
    o = ["# Brief for named-item catalogue sessions", "",
         "> Generated by `tools/design/items/make_brief.py` from the GDDs and `lint_items.py`. Lookup tables only; the rules",
         "> are in `design/items/README.md` and `design/gdd/item-database.md`.", "",
         "## Budget (Formulas I)", "",
         "| Grade | Rarity | Plain-modifier budget | Spend target 80 % | Lint limit (×1.25) | Copies |", "|---|---|---|---|---|---|"]
    for g in (1, 2, 3, 4):
        b = L.AFFIX_COUNT[g] * wa
        o.append("| %d %s | %d | %.1f W | %.1f W | %.1f W | %s |" % (g, ["", "Hạ", "Trung", "Thượng", "Cực"][g], g + 1, b, 0.8 * b,
                                                                  b * L.NAMED_W_TOLERANCE, "unique" if g + 1 >= 5 else "repeatable"))
    o += ["", "An item whose main value is a strong enabler may spend down to 60 %. A reserve art may grant up to 1 W of",
          "modifiers per percentage point of maximum linh lực it reserves, on top of the budget.", "",
          "## How a modifier line is priced", "",
          "`W = |value| × price ÷ breadth(scope)`. Breadth: no scope 1.0; one broad tag 1.25; one family tag 1.5; one narrow",
          "tag 2.0; two tags: one step narrower than the narrower of the two when the second is family or narrower (two",
          "family tags = 2.0). A reduction on a lower-is-better key (art cost, thần thức cost) is the bonus.", "",
          "## Priced keys (W per displayed unit)", "", "| Key | What | W |", "|---|---|---|"]
    keys = dict(L.tech.PRICE)
    keys.update(L.ITEM_PRICE)
    for k in sorted(keys):
        o.append("| `%s` | %s | %s%s |" % (k, names.get(k, ""), keys[k], " (rare: one unit)" if k in ("bonus_slots", "artifact_slots", "bonus_ward_slots") else ""))
    o += ["", "`damage_more`, `ward_more` and `body_more` are Effect payloads only on items, never plain modifiers. `resist_pct` is",
          "in points (W 0.04 per point).", "",
          "## Scope tags (Modifier vocabulary)", ""]
    by = {}
    for t, tier in L.tech.TIER.items():
        by.setdefault(tier, []).append(t)
    for tier in ("broad", "family", "narrow"):
        o.append("- **%s** (÷%s): %s" % (tier, L.tech.MULT[tier], ", ".join(sorted(by.get(tier, [])))))
    o += ["", "Element tags are `kim moc thuy hoa tho` and the variant ids `phong loi am hon_don quang bang`; damage types",
          "`fire cold lightning light chaos physical force soul`; element stacks are scoped `[<element>, buff]` or",
          "`[<element>, debuff]`.", "",
          "## Effects in effects.md", "",
          "Use an existing Effect by its English name (before the bracket). Usable on items when Hosts says Item or Named Item;",
          "others only as a marked exception.", "", "| Effect | Group | Hosts | Rule |", "|---|---|---|---|"]
    for e in gd["effects"]:
        if e["group"].startswith("Status"):
            continue
        o.append("| %s | %s | %s | %s |" % (re.sub(r"\s*\(.*$", "", e["name"]), e["group"], e["hosts"] or "—", e["rule"][:160]))
    cd = open(os.path.join(ROOT, "design", "gdd", "combat-defence.md"), encoding="utf-8").read()
    sec = cd.split("### H. Starter ward catalogue", 1)[1].split("**Body pieces.**")[0]
    rows = [ln for ln in sec.splitlines() if ln.startswith("| ")]
    o += ["", "## Starter wards (Combat Defence & Healing Formulas H)", "",
          "A new ward is a starter ward with its payload and its payment scaled by the same factor, so its price check is",
          "inherited (`check_from` names the starter ward). Keep the payment model and activation.", ""] + rows
    os.makedirs(os.path.join(ROOT, "design", "items", "_logs"), exist_ok=True)
    out = os.path.join(ROOT, "design", "items", "_logs", "brief.md")
    open(out, "w", encoding="utf-8").write("\n".join(o) + "\n")
    print("wrote", os.path.relpath(out, ROOT), len(o), "lines")


if __name__ == "__main__":
    main()
