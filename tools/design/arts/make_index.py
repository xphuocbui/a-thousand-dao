"""Write design/arts/INDEX.md: every library art and catalogue technique on one line, for build authors.

Run: python -I tools/design/arts/make_index.py   (rewrites design/arts/INDEX.md; never hand-edit it)
"""
import glob
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
TIER = {0: "Yellow", 1: "Profound", 2: "Earth", 3: "Heaven"}


def short(s, n=150):
    s = " ".join(str(s).split())
    return s if len(s) <= n else s[:n - 1] + "…"


def main():
    fams = sorted(glob.glob(os.path.join(ROOT, "design", "arts", "family-*.json")))
    techs = []
    for f in sorted(glob.glob(os.path.join(ROOT, "design", "techniques", "catalogue-*.json"))):
        techs += json.load(open(f, encoding="utf-8"))
    carrier = {x["ability_id"]: (t["id"], x["unlock_layer"]) for t in techs for x in t["abilities"]}
    out = ["# Art and Technique Index", "",
           "> Generated by `tools/design/arts/make_index.py` from `design/arts/family-*.json`, the `common` arts of",
           "> `design/arts/part-*.json` and `design/techniques/catalogue-*.json`. Do not edit by hand.",
           "> In a fight file: an art is `{\"lib\": \"<id>\"}`, a technique is an id in `\"techniques\"` (fight.py).", "",
           "## Techniques (công pháp)", "",
           "| Id | Name | Tier, kind | Names | Arts (unlock layer) | Passives |", "|---|---|---|---|---|---|"]
    for t in techs:
        pas = ", ".join("%s %+g%s" % (p["key"], p["value"], (" [" + ",".join(p.get("scope", [])) + "]") if p.get("scope") else "")
                        for p in t["passives"])
        arts = ", ".join("%s (%d)" % (x["ability_id"], x["unlock_layer"]) for x in t["abilities"])
        out.append("| `%s` | %s | %s %s | %s | %s | %s |" % (t["id"], t["name"], TIER[t["tier"]], t["tech_kind"],
                                                            ",".join(t["names"]) or "-", arts, pas))
    out += ["", "## Signature arts (authored)", "",
            "| Id | Element | Role | Power | Suite | Carried by | Rule |", "|---|---|---|---|---|---|---|"]
    for f in fams:
        for a in json.load(open(f, encoding="utf-8")):
            c = carrier.get(a["id"], ("-", 0))
            out.append("| `%s` | %s | %s | %s | %s | %s L%d | %s |" % (a["id"], a.get("element") or "-", a.get("role", ""),
                                                                      a.get("power", ""), a.get("group") or "-", c[0],
                                                                      c[1], short(a.get("rule", ""))))
    out += ["", "## Common arts (rolled by generated techniques, one each, unlocked at layer 1)", "",
            "| Id | Element | Role | Rule |", "|---|---|---|---|"]
    for f in sorted(glob.glob(os.path.join(ROOT, "design", "arts", "part-*.json"))):
        for a in json.load(open(f, encoding="utf-8")):
            if a.get("tier") == "common":
                out.append("| `%s` | %s | %s | %s |" % (a["id"], a.get("element") or "-", a.get("role", ""),
                                                       short(a.get("rule", ""), 100)))
    p = os.path.join(ROOT, "design", "arts", "INDEX.md")
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote %s: %d techniques" % (p, len(techs)))


if __name__ == "__main__":
    main()
