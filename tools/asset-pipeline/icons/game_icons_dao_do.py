"""Framed Đạo Đồ node icons for the game's tree view (design/ux/dao-do-view.md): the same icons the v5 viewer artifact
shows (viewer_icons_dao_do.py: painting cropped into its frame, notable tone, the qi pearl on roads), at game sizes, packed
into sprite sheets under assets/icons/dao_do/game/ with icons.json ({hole, n: {node id: [name, frame, tint]}, atlas:
{name: [sheet, x, y, w]}, sheets: [[file, w, h]]}). The per-icon files stay in a temporary folder; only the sheets ship.

Usage: python tools/asset-pipeline/icons/game_icons_dao_do.py <repo root>
User 2026-11-24: "It should be like PoE's skill tree. Please add with icon" (the icon engine wiring had been deferred to
release on 2026-11-20; this brings it forward). No image API calls: everything is composited from existing paintings.
"""
import os
import shutil
import sys
import tempfile

ROOT = os.path.abspath(sys.argv[1])
HERE = os.path.dirname(os.path.abspath(__file__))
VIEWER = os.path.join(HERE, "viewer_icons_dao_do.py")
OUT = os.path.join(ROOT, "assets", "icons", "dao_do", "game")
# Game sizes (user 2026-11-24: the first build at 0.6x the viewer's looked blurry): about the viewer's size and more, so an
# icon stays sharp up to the deepest zoom (4 sheets, 8.5 MB). Import each sheet VRAM-compressed with mipmaps
# (compress/mode=2, mipmaps/generate=true in its .import): uncompressed with runtime mipmaps they cost ~150 MB of VRAM.
GAME_PX = '{"road": 64, "small": 96, "notable": 128, "capability": 144, "keystone": 208, "start": 224}'

src = open(VIEWER, encoding="utf-8").read()
old = 'PX = {"road": 64, "small": 80, "notable": 112, "capability": 128, "keystone": 176, "start": 192}'
assert old in src, "viewer_icons_dao_do.py changed: update GAME_PX's anchor"
src = src.replace(old, "PX = " + GAME_PX)
tmp = tempfile.mkdtemp(prefix="dd_game_icons_")
try:
    sys.argv = [VIEWER, ROOT, tmp]
    exec(compile(src, VIEWER, "exec"), {"__name__": "__main__", "__file__": VIEWER})
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):   # the previous build's sheets (their .import files are regenerated by Godot)
        if f.startswith("di-sheet-") and f.endswith(".webp") or f == "icons.json":
            os.remove(os.path.join(OUT, f))
    for f in os.listdir(tmp):
        if f.startswith("di-sheet-") or f == "icons.json":
            shutil.copy(os.path.join(tmp, f), os.path.join(OUT, f))
    print("wrote", sorted(f for f in os.listdir(OUT) if not f.endswith(".import")))
finally:
    shutil.rmtree(tmp, ignore_errors=True)
