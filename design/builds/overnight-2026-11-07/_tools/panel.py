#!/usr/bin/env python3
"""Runs every build against the standard enemy panel and writes panel.md.

Observations only. A cell is W (win), L (loss), S (stalemate), D (draw) or F (fled),
with the time, and on a loss the health the enemy kept. Only the orchestrator runs it.
Run from the repo root: python design/builds/overnight-2026-11-07/_tools/panel.py
"""
import glob
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RUNNER = os.path.join(HERE, "fight_x.py")


def cell(text, name):
    res = [l.split("\t") for l in text.splitlines() if l.startswith("result\t")]
    if not res:
        return "?"
    row = res[0]
    t = row[2].replace("t=", "").replace(" s", "")
    t = "%.1f" % float(t)
    end = [l for l in text.splitlines() if l.startswith("end_state\t")]
    m = re.search(r"enemy health (\d+)%", end[0]) if end else None
    left = m.group(1) if m else "?"
    if row[1] == "stalemate":
        return "S %s" % left
    if row[1] == "draw":
        return "D"
    if "flight" in row[1]:
        return "F %s" % t
    if row[3] == "winner=" + str(name):
        return "W %s" % t
    return "L %s" % left


def main():
    panel = json.load(open(os.path.join(HERE, "panel-enemies.json"), encoding="utf-8"))
    panel.pop("_doc")
    names = list(panel)
    tmpdir = os.path.join(ROOT, "scratch", "_panel")
    os.makedirs(tmpdir, exist_ok=True)
    rows = []
    for path in sorted(glob.glob(os.path.join(ROOT, "sheets", "*.fight.json"))):
        slug = os.path.basename(path)[:-len(".fight.json")]
        base = json.load(open(path, encoding="utf-8"))
        cells, wins = [], 0
        for n in names:
            b = dict(base)
            b["enemy_overrides"] = panel[n]
            b.pop("enemy", None)
            tmp = os.path.join(tmpdir, slug + ".json")
            json.dump(b, open(tmp, "w", encoding="utf-8"))
            r = subprocess.run([sys.executable, RUNNER, tmp], capture_output=True, text=True, encoding="utf-8")
            c = cell(r.stdout, base.get("name", slug))
            cells.append(c)
            wins += c.startswith(("W", "F"))
        rows.append((wins, slug, base.get("realm", "?"), cells))
    rows.sort(key=lambda v: (-v[0], v[1]))
    with open(os.path.join(ROOT, "panel.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Enemy Panel\n\nGenerated by `_tools/panel.py`. Each build, unchanged, against five enemy types at its own realm "
                "(`_tools/panel-enemies.json`). W time, or L and the health the enemy kept, S a stalemate, D a draw, F fled and when. "
                "A paper model, and builds were not tuned for this panel. A loss here is information, not a failure: a build needs only "
                "some fights it wins, and several are meant for one kind of enemy.\n\n")
        f.write("| Build | Realm | Won | " + " | ".join(names) + " |\n|---|---|---|" + "---|" * len(names) + "\n")
        for wins, slug, realm, cells in rows:
            f.write("| [%s](sheets/%s.md) | %s | %d of %d | %s |\n" % (slug, slug, realm, wins, len(names), " | ".join(cells)))
    print("panel\t%d builds" % len(rows))
    for n, name in enumerate(names):
        print("%s\twon by %d" % (name, sum(1 for r in rows if r[3][n].startswith(("W", "F")))))
    print("all five\t%d" % sum(1 for r in rows if r[0] == len(names)))
    print("none\t%d" % sum(1 for r in rows if r[0] == 0))


if __name__ == "__main__":
    main()
